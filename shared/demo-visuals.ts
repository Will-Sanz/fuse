export function exampleVisual(
  scenario: 'checkout' | 'shipping',
  path: string,
  conflictId?: string,
): Visual {
  return {
    ...(scenario === 'shipping' ? shippingVisual : checkoutVisual),
    path,
    conflictId,
    origin: 'example',
    provider: 'Prepared example',
    generatedAt: '2026-10-09T00:00:00.000Z',
    generationId: `example-${scenario}`,
    durationMs: 0,
    inputHash: scenario,
    contextFiles: [],
  };
}
